#!/usr/bin/env python3
"""Build and validate the qualified remc2 Level 2 authored/reset census.

The exporter packages are the evidence boundary.  This tool deliberately
decodes their stable, fixed-width records rather than importing Rust structs or
using a fixture generated by the validator itself.  Two independent packages
must be supplied; every byte that contributes to the census is compared before
the machine-readable result is written.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
from typing import Iterable


COMMIT = "6806c7204d17220ecc0430759f784aea8ee2ddb2"
AUTHORED_COUNT = 1200
AUTHORED_BYTES = 20
AUTHORED_OFFSET = 1091
ENTITY_COUNT = 1000
ENTITY_BYTES = 176
PLAYER_COUNT = 8
PLAYER_BYTES = 573
FILES = (
    "authored-level.bin",
    "entities.bin",
    "entities-post-features.bin",
    "feature-allocator.bin",
    "feature-construction-inputs.bin",
    "feature-end.bin",
    "feature-start.bin",
    "players.bin",
    "runtime.bin",
    "presentation.bin",
    "terrain.bin",
    "terrain-post-features.bin",
    "terrain-pre-features.bin",
)
CENSUS_FILES = (
    "authored-level.bin",
    "entities.bin",
    "players.bin",
    "runtime.bin",
    "presentation.bin",
)


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def signed8(value: int) -> int:
    return value - 256 if value >= 128 else value


def signed16(value: int) -> int:
    return value - 65536 if value >= 32768 else value


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def read_manifest(package: Path) -> dict:
    manifest_path = package / "manifest.json"
    require(manifest_path.is_file(), f"missing manifest: {manifest_path}")
    manifest = json.loads(manifest_path.read_text())
    require(manifest.get("schema") == "mc2-owner-level-export/v3", "Level 2 census needs v3 packages")
    level = manifest.get("level", {})
    require(
        level == {"external": 2, "internal": 1, "map_type": {"id": 0, "name": "Day"}},
        f"package is not the qualified external 2/internal 1 Day profile: {level!r}",
    )
    require(manifest.get("counts", {}).get("authored_features") == AUTHORED_COUNT, "manifest authored denominator changed")
    require(manifest.get("counts", {}).get("entity_slots") == ENTITY_COUNT, "manifest entity denominator changed")
    require(manifest.get("counts", {}).get("active_entities") == 114, "manifest Level 2 active count changed")
    require(manifest.get("counts", {}).get("players") == PLAYER_COUNT, "manifest player denominator changed")
    source = manifest.get("source")
    require(isinstance(source, dict), "manifest source provenance is missing")
    require(source.get("upstream_commit") == COMMIT, "manifest source commit does not match the pinned remc2 specification")
    for key in ("upstream_worktree_diff_sha256", "compiled_source_sha256"):
        value = source.get(key)
        require(isinstance(value, str) and len(value) == 64, f"manifest source {key} is not a SHA-256 string")
    for key in ("modified_paths", "modified_files", "compiled_files"):
        require(isinstance(source.get(key), list), f"manifest source {key} is not a list")
    for item in source["compiled_files"]:
        require(isinstance(item, dict), "manifest compiled source entry is not an object")
        require(isinstance(item.get("path"), str) and isinstance(item.get("sha256"), str) and len(item["sha256"]) == 64, "manifest compiled source entry is malformed")
    return manifest


def package_evidence(package: Path) -> dict:
    manifest = read_manifest(package)
    hashes = {}
    sizes = {}
    for name in FILES:
        path = package / name
        require(path.is_file(), f"missing package member {name}")
        data = path.read_bytes()
        hashes[name] = sha256_bytes(data)
        sizes[name] = len(data)
    return {
        "path": str(package),
        "manifest_sha256": sha256_file(package / "manifest.json"),
        "file_sha256": hashes,
        "file_bytes": sizes,
        "manifest_level": manifest["level"],
        "source": manifest["source"],
    }


def compare_packages(first: Path, second: Path) -> tuple[dict, dict]:
    a = package_evidence(first)
    b = package_evidence(second)
    for name in CENSUS_FILES:
        require(
            a["file_sha256"][name] == b["file_sha256"][name],
            f"qualified exports disagree for {name}",
        )
    return a, b


def authored_rows(data: bytes) -> tuple[list[dict], dict]:
    end = AUTHORED_OFFSET + AUTHORED_COUNT * AUTHORED_BYTES
    require(len(data) >= end, "authored-level.bin is truncated before the authored table")
    rows = []
    partitions = {
        "null": [],
        "group_zero_consumed": [],
        "grouped_dormant": [],
        "terrain_auxiliary": [],
        "unassigned_sentinel": [],
    }
    for index in range(AUTHORED_COUNT):
        raw = data[AUTHORED_OFFSET + index * AUTHORED_BYTES : AUTHORED_OFFSET + (index + 1) * AUTHORED_BYTES]
        values = struct.unpack("<HhHHhHhHHH", raw)
        kind, subtype, x, y, group, word10, stage_tag, par1, par2, par3 = values
        if not any(raw):
            state = "null"
        elif group == 0:
            state = "group_zero_consumed"
        elif group == -1:
            state = "unassigned_sentinel"
        elif group > 0 and kind == 0:
            # These 19 rows are authored terrain/command auxiliaries, not
            # dormant creature/building features.
            state = "terrain_auxiliary"
        elif group > 0:
            state = "grouped_dormant"
        else:
            raise ValueError(f"authored row {index} has unknown activation group {group}")
        row = {
            "id": f"AUT-L2-{index:04d}",
            "index": index,
            "state": state,
            "source": {"package_member": "authored-level.bin", "byte_offset": AUTHORED_OFFSET + index * AUTHORED_BYTES, "record_bytes": AUTHORED_BYTES},
            "kind": kind,
            "subtype": subtype,
            "axis": {"x": x, "y": y},
            "activation_group": group,
            "word10": word10,
            "stage_tag": stage_tag,
            "parameter_selectors": {"par1": par1, "par2": par2, "par3": par3},
            "record_hex": raw.hex(),
            "sha256": sha256_bytes(raw),
        }
        rows.append(row)
        partitions[state].append(index)
    return rows, partitions


def entity_role(entity: dict) -> str:
    key = (entity["class"], entity["model"], entity["action"])
    roles = {
        (2, 2, 6): "dolmen",
        (2, 3, 9): "bad_stone",
        (3, 0, 0): "local_wizard",
        (3, 1, 1): "nyphur",
        (5, 1, 9): "goat_action_9",
        (5, 1, 11): "goat_action_11",
        (5, 13, 105): "villager",
        (10, 45, 52): "building",
        (11, 0, 0): "class11_model0",
        (11, 4, 4): "class11_model4",
        (11, 32, 32): "class11_model32",
        (15, 0, 0): "ai_fireball_holder",
        (15, 1, 3): "ai_possession_holder",
        (15, 3, 10): "spell_pickup_model3",
        (15, 12, 37): "spell_pickup_model12",
    }
    if key not in roles:
        raise ValueError(f"unknown Level 2 reset constructor tuple class/model/action={key}")
    return roles[key]


def entity_rows(data: bytes) -> tuple[list[dict], dict]:
    require(data[:4] == b"MCE1", "entities.bin magic mismatch")
    require(struct.unpack_from("<HHI", data, 4) == (1, ENTITY_BYTES, ENTITY_COUNT), "entities.bin header mismatch")
    rows = []
    partitions = {"inactive": [], "active": []}
    for index in range(ENTITY_COUNT):
        offset = 12 + index * ENTITY_BYTES
        raw = data[offset : offset + ENTITY_BYTES]
        require(len(raw) == ENTITY_BYTES, f"entity slot {index} truncated")
        require(struct.unpack_from("<H", raw, 0)[0] == index, f"entity slot {index} stable index mismatch")
        active = bool(raw[2])
        if not active:
            # entities.bin is the reset capture, not the post-feature
            # normalized file.  Inactive native slots retain deterministic
            # index/allocator bytes; the class byte is the authoritative
            # inactive marker.  Do not silently pretend this is the MCE3
            # zero-normalized projection.
            require(raw[67] == 0, f"inactive entity slot {index} has a live class")
        entity = {
            "id": f"RST-L2-{index:04d}",
            "slot": index,
            "partition": "active" if active else "inactive",
            "source": {"package_member": "entities.bin", "byte_offset": offset, "record_bytes": ENTITY_BYTES},
            "active": active,
            "relations": {
                "next": struct.unpack_from("<I", raw, 4)[0],
                "old_map_entity": struct.unpack_from("<H", raw, 26)[0],
                "next_entity": struct.unpack_from("<H", raw, 28)[0],
                "source_id": struct.unpack_from("<H", raw, 30)[0],
                "parent": struct.unpack_from("<H", raw, 44)[0],
                "parameter": struct.unpack_from("<I", raw, 164)[0],
                "special_domain": raw[168],
                "special": struct.unpack_from("<I", raw, 172)[0],
            },
            "class": raw[67],
            "model": raw[68],
            "xtype": signed8(raw[69]),
            "xsubtype": signed8(raw[70]),
            "action": raw[73],
            "stage_vars": {"one": signed8(raw[76]), "two": signed8(raw[77])},
            "position": {"x": struct.unpack_from("<h", raw, 80)[0], "y": struct.unpack_from("<h", raw, 82)[0], "z": struct.unpack_from("<h", raw, 84)[0]},
            "parameter_selector": struct.unpack_from("<I", raw, 164)[0],
            "role": entity_role({"class": raw[67], "model": raw[68], "action": raw[73]}) if active else "inactive",
            "record_hex": raw.hex(),
            "sha256": sha256_bytes(raw),
        }
        rows.append(entity)
        partitions[entity["partition"]].append(index)
    return rows, partitions


def wizard_rows(data: bytes) -> list[dict]:
    base = AUTHORED_OFFSET + AUTHORED_COUNT * AUTHORED_BYTES + 1
    rows = []
    for index in range(PLAYER_COUNT):
        offset = base + index * 110
        raw = data[offset : offset + 110]
        require(len(raw) == 110, f"wizard record {index} truncated")
        rows.append({
            "id": f"WIZ-L2-{index:02d}",
            "index": index,
            "source": {"package_member": "authored-level.bin", "byte_offset": offset, "record_bytes": 110},
            "aggression": struct.unpack_from("<h", raw, 3)[0],
            "reflexes": struct.unpack_from("<h", raw, 7)[0],
            "perception": struct.unpack_from("<h", raw, 11)[0],
            "starting_spells": list(raw[15:41]),
            "spell_levels": list(raw[41:67]),
            "blocked_spells": list(raw[67:93]),
            "life": struct.unpack_from("<h", raw, 93)[0],
            "record_hex": raw.hex(),
            "sha256": sha256_bytes(raw),
        })
    return rows


def stage_rows(data: bytes) -> tuple[list[dict], list[dict]]:
    stages = []
    base = 25972
    for index in range(8):
        offset = base + index * 7
        raw = data[offset : offset + 7]
        stages.append({
            "id": f"STAGE-L2-{index:02d}",
            "index": index,
            "source": {"package_member": "authored-level.bin", "byte_offset": offset, "record_bytes": 7},
            "stage_index": signed8(raw[0]),
            "objective_selector": struct.unpack_from("<h", raw, 1)[0],
            "axis": {"x": struct.unpack_from("<h", raw, 3)[0], "y": struct.unpack_from("<h", raw, 5)[0]},
            "sha256": sha256_bytes(raw),
            "record_hex": raw.hex(),
        })
    variables = []
    base = 26028
    for index in range(11):
        offset = base + index * 8
        raw = data[offset : offset + 8]
        variables.append({
            "id": f"STAGEVAR-L2-{index:02d}",
            "index": index,
            "source": {"package_member": "authored-level.bin", "byte_offset": offset, "record_bytes": 8},
            "index_value": signed8(raw[0]),
            "stage": signed8(raw[1]),
            "selector": struct.unpack_from("<H", raw, 2)[0],
            "axis_or_relation": {"x": struct.unpack_from("<H", raw, 4)[0], "y": struct.unpack_from("<H", raw, 6)[0]},
            "sha256": sha256_bytes(raw),
            "record_hex": raw.hex(),
        })
    return stages, variables


def runtime_sections(data: bytes) -> dict:
    require(data[:4] == b"MCR1" and len(data) == 2754, "runtime.bin layout mismatch")
    specs = {
        "stages": (192, 8, 14),
        "objectives": (304, 8, 11),
        "stage_variables": (392, 11, 12),
        "events": (524, 50, 43),
        "player_inputs": (2674, 8, 10),
    }
    result = {}
    for section, (offset, count, size) in specs.items():
        rows = []
        for index in range(count):
            start = offset + index * size
            raw = data[start : start + size]
            fields = list(raw)
            if section == "stages":
                fields = {"type": raw[0], "flags": raw[1], "scalar": struct.unpack_from("<I", raw, 2)[0], "domain": raw[6], "relation": struct.unpack_from("<I", raw, 10)[0]}
            elif section == "objectives":
                fields = {"objective_type": raw[0], "flags": list(raw[1:8]), "relation": struct.unpack_from("<H", raw, 8)[0], "parameter": raw[10]}
            elif section == "stage_variables":
                fields = {"type": raw[0], "flags": raw[1], "selector": struct.unpack_from("<H", raw, 2)[0], "domain": raw[4], "relation": struct.unpack_from("<I", raw, 8)[0]}
            elif section == "events":
                fields = {"event_type": raw[0], "domain": raw[10], "relation": struct.unpack_from("<I", raw, 14)[0], "payload_sha256": sha256_bytes(raw[18:])}
            elif section == "player_inputs":
                fields = {"enabled": raw[0], "payload": raw[1:].hex()}
            rows.append({"id": f"{section.upper()}-L2-{index:02d}", "index": index, "source": {"package_member": "runtime.bin", "byte_offset": start, "record_bytes": size}, "fields": fields, "record_hex": raw.hex(), "sha256": sha256_bytes(raw)})
        result[section] = {"offset": offset, "record_bytes": size, "count": count, "rows": rows}
    return result


def presentation_sections(data: bytes) -> dict:
    require(data[:4] == b"MCV1", "presentation.bin magic mismatch")
    particle_count = struct.unpack_from("<I", data, 8)[0]
    require(particle_count == 347, "presentation particle denominator changed")
    particle_offset = 12
    particle_size = 14
    particles = []
    for index in range(particle_count):
        start = particle_offset + index * particle_size
        raw = data[start : start + particle_size]
        particles.append({"id": f"PARTICLE-L2-{index:03d}", "index": index, "source": {"package_member": "presentation.bin", "byte_offset": start, "record_bytes": particle_size}, "bytes": raw.hex(), "record_hex": raw.hex(), "sha256": sha256_bytes(raw)})
    sprite_count_offset = particle_offset + particle_count * particle_size
    sprite_count = struct.unpack_from("<I", data, sprite_count_offset)[0]
    require(sprite_count == 504, "presentation selector denominator changed")
    sprite_offset = sprite_count_offset + 4
    selectors = []
    for index in range(sprite_count):
        raw = data[sprite_offset + index : sprite_offset + index + 1]
        selectors.append({"id": f"SPRITESEL-L2-{index:03d}", "index": index, "selector": raw[0], "source": {"package_member": "presentation.bin", "byte_offset": sprite_offset + index, "record_bytes": 1}, "record_hex": raw.hex(), "sha256": sha256_bytes(raw)})
    parameter_count_offset = sprite_offset + sprite_count
    parameter_count = struct.unpack_from("<I", data, parameter_count_offset)[0]
    require(parameter_count == 157, "presentation entity parameter denominator changed")
    parameter_offset = parameter_count_offset + 4
    parameters = []
    for index in range(parameter_count):
        start = parameter_offset + index * 34
        raw = data[start : start + 34]
        parameters.append({"id": f"ENTITYPARAM-L2-{index:03d}", "index": index, "source": {"package_member": "presentation.bin", "byte_offset": start, "record_bytes": 34}, "bytes": raw.hex(), "record_hex": raw.hex(), "sha256": sha256_bytes(raw)})
    require(parameter_offset + parameter_count * 34 == len(data), "presentation.bin has dropped or unknown tail bytes")
    return {
        "particle_parameters": {"count": particle_count, "record_bytes": particle_size, "rows": particles},
        "sprite_selectors": {"count": sprite_count, "record_bytes": 1, "rows": selectors},
        "entity_parameters": {"count": parameter_count, "record_bytes": 34, "rows": parameters},
    }


def build(first: Path, second: Path) -> dict:
    evidence_a, evidence_b = compare_packages(first, second)
    authored_data = (first / "authored-level.bin").read_bytes()
    entities_data = (first / "entities.bin").read_bytes()
    players_data = (first / "players.bin").read_bytes()
    runtime_data = (first / "runtime.bin").read_bytes()
    presentation_data = (first / "presentation.bin").read_bytes()
    require(len(authored_data) == 0x6604, "authored-level.bin byte extent changed")
    require(players_data[:4] == b"MCP1" and struct.unpack_from("<HHI", players_data, 4) == (2, PLAYER_BYTES, PLAYER_COUNT), "players.bin layout mismatch")
    players = []
    for index in range(PLAYER_COUNT):
        offset = 12 + index * PLAYER_BYTES
        raw = players_data[offset : offset + PLAYER_BYTES]
        players.append({"id": f"PLAYER-L2-{index:02d}", "slot": index, "entity_slot": struct.unpack_from("<H", raw, 4)[0], "source": {"package_member": "players.bin", "byte_offset": offset, "record_bytes": PLAYER_BYTES}, "record_hex": raw.hex(), "sha256": sha256_bytes(raw)})
    authored, authored_partitions = authored_rows(authored_data)
    entities, entity_partitions = entity_rows(entities_data)
    stages, stage_variables = stage_rows(authored_data)
    pickup_rows = [
        {"index": row["index"], "subtype": row["subtype"], "activation_group": row["activation_group"], "label": {6: "Speed", 11: "Beyond Sight"}.get(row["subtype"], "unknown")}
        for row in authored
        if row["kind"] == 15 and row["subtype"] in (6, 11)
    ]
    active_entities = [row for row in entities if row["active"]]
    constructor_groups = {}
    for row in active_entities:
        key = (row["class"], row["model"], row["action"])
        constructor_groups.setdefault(key, []).append(row["slot"])
    constructors = [
        {
            "id": f"CTOR-L2-{class_id:02d}-{model:03d}-{action:03d}",
            "class": class_id,
            "model": model,
            "action": action,
            "count": len(slots),
            "reset_slots": slots,
        }
        for (class_id, model, action), slots in sorted(constructor_groups.items())
    ]
    census = {
        "schema": "mc2-level2-authored-reset-census/v1",
        "spec": {"remc2_commit": COMMIT, "qualified_profile": {"external": 2, "internal": 1, "map_type": "Day"}, "scope": "denominator and reset census; no simulation-completeness claim"},
        "qualified_exports": [evidence_a, evidence_b],
        "authored": {"record_count": AUTHORED_COUNT, "record_bytes": AUTHORED_BYTES, "table_offset": AUTHORED_OFFSET, "rows": authored, "partitions": authored_partitions, "partition_counts": {key: len(value) for key, value in authored_partitions.items()}},
        "reset": {"slot_count": ENTITY_COUNT, "record_bytes": ENTITY_BYTES, "active_count": len(entity_partitions["active"]), "slots": entities, "partitions": entity_partitions, "partition_counts": {key: len(value) for key, value in entity_partitions.items()}},
        "constructors": constructors,
        "wizard_player": {"wizard_records": wizard_rows(authored_data), "player_records": players},
        "runtime": runtime_sections(runtime_data),
        "presentation": presentation_sections(presentation_data),
        "stages": stages,
        "stage_variables": stage_variables,
        "authored_pickups": pickup_rows,
        "known_cross_checks": {"dolmens": [108, 109, 110], "bad_stones": [33, 34, 35, 36], "local_wizard": [111], "nyphur": [112], "goats_action_9": 34, "goats_action_11": 2, "villagers": 29, "buildings": 22, "class11_models": {"0": 10, "4": 1, "32": 3}, "spell_holders": {"ai_fireball": 113, "ai_possession": 114}, "pickups": ["Speed", "Beyond Sight"]},
    }
    validate(census)
    return census


def validate(census: dict) -> None:
    require(census.get("schema") == "mc2-level2-authored-reset-census/v1", "census schema mismatch")
    require(census["spec"]["remc2_commit"] == COMMIT, "census spec commit mismatch")
    exports = census.get("qualified_exports")
    require(isinstance(exports, list) and len(exports) == 2, "census must retain exactly two qualified export receipts")
    for receipt in exports:
        source = receipt.get("source")
        require(isinstance(source, dict) and source.get("upstream_commit") == COMMIT, "qualified export source provenance is missing or wrong")
        for key in ("upstream_worktree_diff_sha256", "compiled_source_sha256"):
            require(isinstance(source.get(key), str) and len(source[key]) == 64, f"qualified export source {key} is malformed")
        for key in ("modified_paths", "modified_files", "compiled_files"):
            require(isinstance(source.get(key), list), f"qualified export source {key} is malformed")
        require(all(isinstance(item, dict) and isinstance(item.get("path"), str) and len(item.get("sha256", "")) == 64 for item in source["compiled_files"]), "qualified export compiled file provenance is malformed")
    source_fields = ("upstream_worktree_diff_sha256", "compiled_source_sha256", "modified_paths", "modified_files", "compiled_files", "owner_files")
    for key in source_fields:
        require(exports[0]["source"].get(key) == exports[1]["source"].get(key), f"qualified export provenance differs for {key}")
    for name in CENSUS_FILES:
        require(exports[0]["file_sha256"].get(name) == exports[1]["file_sha256"].get(name), f"qualified exports disagree for census member {name}")
    authored = census["authored"]
    rows = authored["rows"]
    require(len(rows) == AUTHORED_COUNT, "dropped or extra authored rows")
    require([row["index"] for row in rows] == list(range(AUTHORED_COUNT)), "authored rows are not stable ordered IDs")
    require(sum(authored["partition_counts"].values()) == AUTHORED_COUNT, "authored partition does not cover denominator")
    require(authored["partition_counts"] == {"null": 755, "group_zero_consumed": 158, "grouped_dormant": 246, "terrain_auxiliary": 19, "unassigned_sentinel": 22}, f"authored partition counts changed: {authored['partition_counts']}")
    derived_partitions = {key: [] for key in authored["partitions"]}
    for row in rows:
        raw = bytes.fromhex(row.get("record_hex", ""))
        require(len(raw) == AUTHORED_BYTES and row.get("sha256") == sha256_bytes(raw), f"authored row {row.get('index')} hash/record mismatch")
        values = struct.unpack("<HhHHhHhHHH", raw)
        kind, _, _, _, group, _, _, _, _, _ = values
        if not any(raw):
            state = "null"
        elif group == 0:
            state = "group_zero_consumed"
        elif group == -1:
            state = "unassigned_sentinel"
        elif group > 0 and kind == 0:
            state = "terrain_auxiliary"
        elif group > 0:
            state = "grouped_dormant"
        else:
            raise ValueError(f"authored row {row['index']} has unknown activation group")
        require(row["state"] == state, f"authored row {row['index']} state differs from its record")
        derived_partitions[state].append(row["index"])
    require(derived_partitions == authored["partitions"], "authored partition does not match row-derived ownership")
    for state, indices in authored["partitions"].items():
        require(len(indices) == len(set(indices)), f"duplicate authored ownership in {state}")
        require(all(rows[index]["state"] == state for index in indices), f"authored partition row mismatch in {state}")
    require(set().union(*(set(values) for values in authored["partitions"].values())) == set(range(AUTHORED_COUNT)), "authored partition dropped or multiply-owned rows")

    reset = census["reset"]
    slots = reset["slots"]
    require(len(slots) == ENTITY_COUNT and [row["slot"] for row in slots] == list(range(ENTITY_COUNT)), "reset slots are not a complete stable partition")
    require(reset["active_count"] == 114, "Level 2 reset active denominator changed")
    require(reset["partition_counts"] == {"inactive": 886, "active": 114}, f"reset partition counts changed: {reset['partition_counts']}")
    require(set().union(*(set(values) for values in reset["partitions"].values())) == set(range(ENTITY_COUNT)), "reset partition dropped or multiply-owned slots")
    derived_reset = {"inactive": [], "active": []}
    for row in slots:
        raw = bytes.fromhex(row.get("record_hex", ""))
        require(len(raw) == ENTITY_BYTES and row.get("sha256") == sha256_bytes(raw), f"reset slot {row.get('slot')} hash/record mismatch")
        slot = row["slot"]
        require(struct.unpack_from("<H", raw, 0)[0] == slot, f"reset slot {slot} source index mismatch")
        partition = "active" if bool(raw[2]) else "inactive"
        require(row["partition"] == partition, f"reset slot {slot} partition differs from its record")
        derived_reset[partition].append(slot)
        require(row["relations"]["next"] == struct.unpack_from("<I", raw, 4)[0], f"reset slot {slot} next relation mismatch")
        require(row["relations"]["source_id"] == struct.unpack_from("<H", raw, 30)[0], f"reset slot {slot} source relation mismatch")
        require(row["relations"]["parent"] == struct.unpack_from("<H", raw, 44)[0], f"reset slot {slot} parent relation mismatch")
        require(row["class"] == raw[67] and row["model"] == raw[68] and row["action"] == raw[73], f"reset slot {slot} constructor tuple mismatch")
        if partition == "active":
            require(row["role"] == entity_role({"class": raw[67], "model": raw[68], "action": raw[73]}), f"reset slot {slot} constructor role mismatch")
    require(derived_reset == reset["partitions"], "reset partition does not match row-derived ownership")
    active = [row for row in slots if row["active"]]
    require([row["slot"] for row in active] == list(range(1, 115)), "reset active rows are not the preserved prefix 1..114")
    require(all(0 <= row["relations"]["next"] <= ENTITY_COUNT for row in active), "unknown reset next relation")
    require(all(0 <= row["relations"]["parameter"] <= 157 for row in active), "unknown reset parameter selector")
    require(all(row["relations"]["special_domain"] in (1, 2) for row in active), "unknown reset special relation domain")

    role_counts = {}
    for row in active:
        role_counts[row["role"]] = role_counts.get(row["role"], 0) + 1
    require(role_counts.get("dolmen") == 3, "dolmen reset census mismatch")
    require(role_counts.get("bad_stone") == 4, "bad-stone reset census mismatch")
    require(role_counts.get("local_wizard") == 1 and role_counts.get("nyphur") == 1, "wizard reset census mismatch")
    require(role_counts.get("goat_action_9") == 34 and role_counts.get("goat_action_11") == 2, "goat action census mismatch")
    require(role_counts.get("villager") == 29 and role_counts.get("building") == 22, "resident/building reset census mismatch")
    require({str(model): role_counts.get(f"class11_model{model}", 0) for model in (0, 4, 32)} == {"0": 10, "4": 1, "32": 3}, "class-11 reset census mismatch")
    require(role_counts.get("ai_fireball_holder") == 1 and role_counts.get("ai_possession_holder") == 1, "AI spell-holder reset census mismatch")
    require(len(census["wizard_player"]["wizard_records"]) == 8 and len(census["wizard_player"]["player_records"]) == 8, "wizard/player denominator mismatch")
    for group_name in ("wizard_records", "player_records"):
        for row in census["wizard_player"][group_name]:
            raw = bytes.fromhex(row.get("record_hex", ""))
            expected_size = 110 if group_name == "wizard_records" else PLAYER_BYTES
            require(len(raw) == expected_size and row.get("sha256") == sha256_bytes(raw), f"{group_name} row {row.get('index', row.get('slot'))} hash/record mismatch")
    for row in census["wizard_player"]["player_records"]:
        require(0 <= row["entity_slot"] < ENTITY_COUNT, f"player slot {row['slot']} entity relation out of range")
        raw = bytes.fromhex(row["record_hex"])
        require(row["entity_slot"] == struct.unpack_from("<H", raw, 4)[0], f"player slot {row['slot']} entity relation differs from players.bin")
        if row["slot"] < 2:
            require(census["reset"]["slots"][row["entity_slot"]]["active"], f"local Level 2 player slot {row['slot']} does not reference an active reset entity")
    require(len(census["stages"]) == 8 and len(census["stage_variables"]) == 11, "stage denominator mismatch")
    for group_name, expected_size in (("stages", 7), ("stage_variables", 8)):
        for row in census[group_name]:
            raw = bytes.fromhex(row.get("record_hex", ""))
            require(len(raw) == expected_size and row.get("sha256") == sha256_bytes(raw), f"{group_name} row {row['index']} hash/record mismatch")
    require(census["authored_pickups"] == [{"index": 155, "subtype": 6, "activation_group": 22, "label": "Speed"}, {"index": 156, "subtype": 11, "activation_group": 27, "label": "Beyond Sight"}], "Level 2 pickup authored rows changed")
    require(len(census["runtime"]["objectives"]["rows"]) == 8, "objective denominator mismatch")
    for section in census["runtime"].values():
        for row in section["rows"]:
            raw = bytes.fromhex(row.get("record_hex", ""))
            require(row.get("sha256") == sha256_bytes(raw), f"runtime row {row['id']} hash/record mismatch")
    require(len(census["presentation"]["sprite_selectors"]["rows"]) == 504, "presentation selector denominator mismatch")
    for section in census["presentation"].values():
        for row in section["rows"]:
            raw = bytes.fromhex(row.get("record_hex", ""))
            require(row.get("sha256") == sha256_bytes(raw), f"presentation row {row['id']} hash/record mismatch")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("first", type=Path, nargs="?", help="first qualified Level 2 package")
    parser.add_argument("second", type=Path, nargs="?", help="second qualified Level 2 package")
    parser.add_argument("--output", type=Path, help="census JSON output")
    parser.add_argument("--validate", type=Path, help="validate an existing census JSON instead of rebuilding")
    args = parser.parse_args()
    if args.validate:
        validate(json.loads(args.validate.read_text()))
        print(f"PASS: {args.validate} validated")
        return 0
    if not args.first or not args.second or not args.output:
        parser.error("first package, second package, and --output are required when building")
    census = build(args.first, args.second)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(census, indent=2, sort_keys=True) + "\n")
    print(f"PASS: wrote {args.output} ({len(census['authored']['rows'])} authored rows, {len(census['reset']['slots'])} reset slots)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
