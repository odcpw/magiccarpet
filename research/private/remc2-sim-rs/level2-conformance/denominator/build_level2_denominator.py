TABLE_RE = re.compile(
    r"type_D4C52ar2\s+x_DWORD_D4C52ar_str(?P<class>[0-9A-F])(?P<kind>[01])"
    r"\[(?P<size>\d+)\]\s*=\s*\{(?P<body>.*?)\};",
    re.DOTALL,
)
TOKEN_RE = re.compile(r"0x[0-9A-Fa-f]+|\b\d+\b")
CASE_RE = re.compile(r"case\s+0x(?P<address>[0-9A-Fa-f]+)\s*:")
CALL_RE = re.compile(r"\b(?P<name>[A-Za-z_]\w*)\s*\(")
FUNCTION_RE = re.compile(
    r"(?m)^\s*(?:[A-Za-z_][\w:<>,~*&\[\]]*\s+)+"
    r"(?P<name>[A-Za-z_]\w*)\s*\([^;{}]*\)\s*(?://[^\n]*)?\n\s*\{"
)
LCG_RE = re.compile(r"9377\s*\*\s*[^;\n]+\+\s*9439|\brand_0x(?:8|14_20)\b|\bwatcomrand\s*\(")
PRESENTATION_RE = re.compile(
    r"TMAP|BUILD|build|sprite|Sprite|SPRITE|HUD|Hud|text|Text|TEXT|music|Music|MUSIC|Render|render|DrawBar|StatusBar|mana|health"
)
IGNORED_CALLS = {
    "if", "for", "while", "switch", "return", "sizeof", "catch", "static_cast",
    "reinterpret_cast", "const_cast", "DoDebugSequences", "DoDebugafterload",
}


def fail(message: str) -> None:
    raise ValueError(message)


def source_file(path: str) -> str:
    try:
        result = subprocess.run(
            ["git", "-C", str(UPSTREAM), "show", f"{COMMIT}:{path}"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        fail(f"cannot read pinned source {path}: {exc}")
    return result.stdout


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def line_number(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def strip_comments(text: str) -> str:
    def replace(match: re.Match[str]) -> str:
        return "".join("\n" if c == "\n" else " " for c in match.group(0))

    return re.sub(r"//[^\n]*|/\*.*?\*/", replace, text, flags=re.DOTALL)


def function_bodies(text: str) -> dict[str, dict[str, object]]:
    """Return definitions with balanced bodies and pinned line/hash identity."""
    result: dict[str, dict[str, object]] = {}
    for match in FUNCTION_RE.finditer(text):
        name = match.group("name")
        brace = text.find("{", match.start(), match.end())
        depth = 0
        end = None
        for pos in range(brace, len(text)):
            if text[pos] == "{":
                depth += 1
            elif text[pos] == "}":
                depth -= 1
                if depth == 0:
                    end = pos + 1
                    break
        if end is None:
            continue
        body = text[match.start() : end]
        body_start_line = line_number(text, brace) + 1
        result.setdefault(
            name,
            {
                "name": name,
                "start_line": line_number(text, match.start()),
                "body_start_line": body_start_line,
                "end_line": line_number(text, end - 1),
                "body": body,
                "body_sha256": sha256(body),
            },
        )
    return result


def call_graph(functions: dict[str, dict[str, object]]) -> dict[str, list[str]]:
    names = set(functions)
    graph: dict[str, list[str]] = {}
    for name, item in functions.items():
        body = strip_comments(str(item["body"]))
        body = body[body.find("{") + 1 :]
        calls = sorted({m.group("name") for m in CALL_RE.finditer(body)} & names - IGNORED_CALLS)
        graph[name] = calls
    return graph


def transitive_closure(graph: dict[str, list[str]], roots: Iterable[str]) -> set[str]:
    seen: set[str] = set()
    todo = deque(roots)
    while todo:
        name = todo.popleft()
        if name in seen:
            continue
        seen.add(name)
        todo.extend(graph.get(name, ()))
    return seen


def dispatcher_address_map(source: str, first: str, second: str) -> tuple[dict[int, str], set[int]]:
    start = source.index(first)
    end = source.index(second, start + len(first))
    body = strip_comments(source[start:end])
    output: dict[int, str] = {}
    cases: set[int] = set()
    labels = list(CASE_RE.finditer(body))
    for index, label in enumerate(labels):
        address = int(label.group("address"), 16)
        cases.add(address)
        stop = labels[index + 1].start() if index + 1 < len(labels) else len(body)
        case_body = body[label.end() : stop]
        calls = [m.group("name") for m in CALL_RE.finditer(case_body) if m.group("name") not in IGNORED_CALLS]
        if calls:
            output[address] = calls[0]
    return output, cases


def parse_dispatch_rows(table_source: str, events_source: str, active_actions: set[tuple[int, int]], active_models: set[tuple[int, int]]) -> list[dict[str, object]]:
    clean = strip_comments(table_source)
    action_map, action_cases = dispatcher_address_map(
        events_source, "void pre_sub_4A190_0x6E8E", "type_entity_0x6E8E* pre_sub_4A190_axis_3d"
    )
    constructor_map, constructor_cases = dispatcher_address_map(
        events_source, "type_entity_0x6E8E* pre_sub_4A190_axis_3d", "type_entity_0x6E8E* IfSubtypeCallCreatingManaSphere_4A190"
    )
    rows: list[dict[str, object]] = []
    seen_tables: set[tuple[int, str]] = set()
    for match in TABLE_RE.finditer(clean):
        runtime_class = int(match.group("class"), 16)
        table_kind = "action" if match.group("kind") == "0" else "constructor"
        size = int(match.group("size"))
        key = (runtime_class, table_kind)
        if key in seen_tables:
            fail(f"duplicate dispatch table {key}")
        seen_tables.add(key)
        tokens = list(TOKEN_RE.finditer(match.group("body")))
        if len(tokens) != size * 4:
            fail(f"{key}: expected {size * 4} tokens, got {len(tokens)}")
        for slot in range(size):
            values = [int(tokens[slot * 4 + i].group(0), 0) for i in range(4)]
            group, selector, address, enabled = values
            sentinel = values == [0, 0, 0, 0]
            amap = action_map if table_kind == "action" else constructor_map
            cases = action_cases if table_kind == "action" else constructor_cases
            fn = amap.get(address, "")
            tuple_key = (runtime_class, selector)
            if sentinel:
                classification = "null_sentinel"
            elif not enabled:
                classification = "disabled_slot"
            elif tuple_key in (active_actions if table_kind == "action" else active_models):
                classification = "reachable_no_call" if not fn and address in cases else "reachable_level2"
            else:
                classification = "mechanically_unreachable_level2"
            token = tokens[slot * 4]
            rows.append({
                "id": f"DSP-L2-{len(rows):03d}",
                "runtime_class": runtime_class,
                "table_kind": table_kind,
                "physical_slot": slot,
                "selector_word_4": selector,
                "group_token_hex": f"0x{group:08X}",
                "stored_address_hex": f"0x{address:08X}" if address else "",
                "enabled_raw": enabled,
                "enabled": bool(enabled),
                "is_null_sentinel": sentinel,
                "resolved_function": fn,
                "dispatcher_case_present": address in cases,
                "classification": classification,
                "source": {"path": "remc2/engine/EventsFunctions.cpp", "line": line_number(clean, match.start("body") + token.start())},
            })
    expected = {(c, k) for c in range(1, 16) for k in ("action", "constructor")}
    if seen_tables != expected:
        fail(f"dispatch table coverage mismatch: missing={sorted(expected - seen_tables)}")
    rows.sort(key=lambda row: (int(row["runtime_class"]), 0 if row["table_kind"] == "action" else 1, int(row["physical_slot"])))
    return rows


def authored_tuple_inputs(census: dict[str, object]) -> tuple[set[tuple[int, int]], set[tuple[int, int]], list[dict[str, object]]]:
    actions: set[tuple[int, int]] = set()
    models: set[tuple[int, int]] = set()
    tuples: list[dict[str, object]] = []
    for ctor in census["constructors"]:  # type: ignore[index]
        cls, model, action = int(ctor["class"]), int(ctor["model"]), int(ctor["action"])
        models.add((cls, model)); actions.add((cls, action))
        tuples.append({"id": ctor["id"], "origin": "reset_constructor", "runtime_class": cls, "model": model, "action": action, "count": ctor["count"], "reset_slots": ctor["reset_slots"]})
    for row in census["authored"]["rows"]:  # type: ignore[index]
        cls, subtype = int(row["kind"]), int(row["subtype"])
        if not cls:
            continue
        actions.add((cls, subtype))
        tuples.append({"id": row["id"], "origin": "authored_event", "runtime_class": cls, "model": None, "action": subtype, "count": 1, "authored_index": row["index"], "activation_group": row["activation_group"]})
    tuples.sort(key=lambda row: (str(row["origin"]), int(row["runtime_class"]), row["action"] if row["action"] is not None else -1, str(row["id"])))
    return actions, models, tuples


def function_ledger(functions: dict[str, dict[str, object]], graph: dict[str, list[str]], roots: Iterable[str], category: str) -> list[dict[str, object]]:
    closure = transitive_closure(graph, roots)
    rows: list[dict[str, object]] = []
    for name in sorted(closure):
        if name not in functions:
            continue
        item = functions[name]
        body = strip_comments(str(item["body"]))
        body = body[body.find("{") + 1 :]
        calls = graph.get(name, [])
        if name in {"sub_12A70", "sub_12E70"}:
            helper_role = "common_tail"
        elif name in {"sub_12FF0", "sub_13100", "sub_131F0", "sub_13270", "sub_133B0", "sub_135C0", "sub_13710", "sub_13830", "sub_13850", "sub_13870", "sub_161A0"}:
            helper_role = "mode"
        elif name in {"sub_164B0", "sub_16580", "sub_16730"}:
            helper_role = "castle_logic"
        elif name in {"sub_169C0", "sub_16CA0", "sub_16E70", "sub_16FC0"}:
            helper_role = "death_respawn"
        elif re.search(r"target|range|distance|nearest|fov|attack|enemy", body, re.I):
            helper_role = "targeting"
        elif re.search(r"move|speed|yaw|roll|position|path", body, re.I):
            helper_role = "movement"
        elif re.search(r"spell|mana|cast|projectile", body, re.I):
            helper_role = "casting"
        elif re.search(r"castle|building|house|dolmen", body, re.I):
            helper_role = "castle_logic"
        elif re.search(r"death|dead|life|respawn|reclaim|kill", body, re.I):
            helper_role = "death_respawn"
        else:
            helper_role = "common_tail"
        rows.append({
            "id": f"{category.upper()}-{len(rows):04d}",
            "symbol": name,
            "category": category,
            "helper_role": helper_role,
            "classification": "reachable_level2",
            "start_line": item["start_line"],
            "end_line": item["end_line"],
            "body_sha256": item["body_sha256"],
            "calls": calls,
            "source_anchor": {"path": "remc2/engine/EventsFunctions.cpp", "symbol": name, "line": item["start_line"], "commit": COMMIT},
            "evidence": "pinned function definition reached by the production dispatch closure",
        })
    return rows


def source_occurrences(path: str, text: str, functions: dict[str, dict[str, object]], closure: set[str], kind: str) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    lines = text.splitlines()
    clean_lines = strip_comments(text).splitlines()
    # Build symbol ranges once so occurrences carry their enclosing owner.
    ranges = [(str(item["start_line"]), name, int(item.get("body_start_line", item["start_line"])), int(item["end_line"])) for name, item in functions.items()]
    for line_no, line in enumerate(lines, 1):
        clean_line = clean_lines[line_no - 1] if line_no <= len(clean_lines) else ""
        if not clean_line.strip() or clean_line.lstrip().startswith("#"):
            continue
        if kind == "rng":
            # A site is a mutation/derivation/seed operation, not every read
            # of a random field in a comment or declaration.  Modulo/bitmask
            # derivations remain sites when they use an RNG field explicitly.
            actual_rng = bool(
                "9377" in clean_line
                or "watcomrand(" in clean_line
                or ("rand_0x" in clean_line and any(token in clean_line for token in ("%", "&", "=", "+", "-")))
                or (path.endswith("Terrain.cpp") and "seed_0x2FEE5" in clean_line)
            )
            if not actual_rng:
                continue
        match = LCG_RE.search(clean_line) if kind == "rng" else PRESENTATION_RE.search(clean_line)
        if not match:
            continue
        owner = "file_scope"
        for _, name, start, end in ranges:
            if start <= line_no <= end:
                owner = name
                break
        if kind == "presentation_ref" and owner == "file_scope":
            continue
        reachable = owner in closure
        profile_exclusion_id = None
        if kind == "rng":
            if "9377" in line:
                rng_kind = "lcg_advance"
            elif "watcomrand" in line:
                rng_kind = "watcomrand_call"
            elif "rand_0x8" in line:
                rng_kind = "global_rng_read_or_transfer"
            else:
                rng_kind = "entity_rng_read_or_transfer"
            branch_token = ""
            for prior in reversed(clean_lines[max(0, line_no - 20) : line_no - 1]):
                if re.search(r"\b(if|else|switch|case|for|while)\b", prior):
                    branch_token = prior.strip()
                    break
            order_token = f"{path}:{line_no}"
            profile_exclusion_id = "EXC-L2-DAY-NO-CAVE" if path.endswith("EventsFunctions.cpp") and line_no in {59842, 59843, 59844, 59847} else None
        else:
            token = match.group(0)
            if token.lower().startswith("tmap"):
                dependency_kind = "TMAP"
            elif token.lower().startswith("build"):
                dependency_kind = "BUILD"
            elif "sprite" in token.lower():
                dependency_kind = "sprite"
            elif "hud" in token.lower() or "drawbar" in token.lower() or "statusbar" in token.lower() or "mana" in token.lower() or "health" in token.lower():
                dependency_kind = "HUD"
            elif "music" in token.lower():
                dependency_kind = "music"
            else:
                dependency_kind = "text_or_render"
        rows.append({
            "id": f"{kind.upper()}-{len(rows):04d}",
            "path": path,
            "line": line_no,
            "enclosing_symbol": owner,
            "expression": clean_line.strip(),
            "classification": "reachable_level2" if reachable and not profile_exclusion_id else "mechanically_unreachable_level2",
            "source_sha256": sha256(text),
            "proof": ("pinned runtime owner expression in the selected Level 2 presentation module" if kind == "presentation_ref" and reachable else "enclosing symbol is in the pinned dispatch/helper closure" if reachable else "enclosing symbol is outside the Level 2 closure"),
            **({"rng_kind": rng_kind, "branch_token": branch_token, "order_token": order_token, "normalized_expression": clean_line.strip(), "profile_exclusion_id": profile_exclusion_id, "profile": {"external": 2, "internal": 1, "map_type": "Day"}} if kind == "rng" else {"dependency_kind": dependency_kind, "root_binding": reachable, "owner": {"native": "remc2-sim-rs owner package", "unity": "owner presentation bridge"}}),
        })
    return rows


def audio_rows(audio: dict[str, object], closure: set[str], dispatch_bindings: dict[str, list[str]], transition_bindings: dict[str, list[str]], helper_paths: dict[str, list[str]]) -> list[dict[str, object]]:
    records = audio["records"]  # type: ignore[index]
    if len(records) != 119:
        fail(f"audio source ledger changed: expected 119, got {len(records)}")
    rows: list[dict[str, object]] = []
    seen: set[str] = set()
    for index, record in enumerate(records, 1):
        key = f"{record['path']}:{record['file_ordinal_1based']}:{record['symbol_ordinal_1based']}:{record['stable_occurrence_hash_sha256']}"
        if key in seen:
            fail(f"duplicate audio identity {key}")
        seen.add(key)
        symbol = str(record["enclosing_symbol"])
        dispatch_roots = set(dispatch_bindings.get(symbol, []))
        transition_roots = set(transition_bindings.get(symbol, []))
        ui_root = symbol in {"AdjustVolume_1A070", "SetMenuCursorPosition_52E90"}
        constructor_root = symbol == "pre_sub_4A190_0x6E8E"
        level1_exclusion_id = record["classification"].get("exclusion_id")
        # A transitive function edge is not enough to defeat a source branch
        # guard (cave/multiplayer, excluded model bands, REST slots, etc.).
        # Keep those exact occurrences excluded until a later profile supplies
        # a discriminating branch proof.
        branch_guarded = bool(level1_exclusion_id)
        reachable = (symbol in closure or bool(dispatch_roots) or ui_root or constructor_root or bool(transition_roots)) and not branch_guarded
        if reachable:
            if symbol in closure:
                proof = "enclosing symbol reached by an active Level 2 constructor/action dispatch root"
            elif ui_root:
                proof = "selected desktop 320x200 UI root retained by the Level 2 profile"
            elif constructor_root:
                proof = "pinned constructor dispatcher root; constructor table is a Level 2 owner"
            else:
                proof = "pinned Level 2 transition/objective root retained by activation closure"
        else:
            proof = (f"preserved Level 1 branch exclusion {level1_exclusion_id}; Level 2 has no reviewed branch override" if branch_guarded else "exact source occurrence retained as an intentional Level 2 exclusion; no active dispatch, UI, or transition root binds it")
        rows.append({
            "id": f"AUD-L2-{index:03d}",
            "path": record["path"],
            "enclosing_symbol": symbol,
            "file_ordinal_1based": record["file_ordinal_1based"],
            "symbol_ordinal_1based": record["symbol_ordinal_1based"],
            "pinned_line": record["pinned_line"],
            "normalized_call_expression": record["normalized_call_expression"],
            "stable_occurrence_hash_sha256": record["stable_occurrence_hash_sha256"],
            "owner_expression": record["entity_owner_expression"],
            "auxiliary_owner_expression": record["auxiliary_owner_expression"],
            "sound_expression": record["sound_expression"],
            "classification": "reachable_level2" if reachable else "mechanically_unreachable_level2",
            "level1_disposition": record["classification"]["disposition"],
            "dispatch_bindings": sorted(dispatch_roots),
            "transition_bindings": sorted(transition_roots),
            "helper_path": helper_paths.get(symbol, []),
            "profile": {"external": 2, "internal": 1, "map_type": "Day"},
            "branch_evidence": {"source_line": record["pinned_line"], "level1_exclusion_id": level1_exclusion_id, "level1_proof": record["classification"].get("producer_or_profile_proof"), "guarded": branch_guarded},
            "proof": proof,
        })
    return rows


def presentation_rows(census: dict[str, object]) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    rows: list[dict[str, object]] = []
    roots: list[dict[str, object]] = []
    import struct

    active_parameters: set[int] = set()
    active_particles: set[int] = set()
    active_sprites: set[int] = set()
    yaw_lookup = (0, 0, 0, 1, 1, 1, 2, 2, 2, 2, 2, 1, 1, 1, 0, 0)
    particle_rows = census["presentation"]["particle_parameters"]["rows"]  # type: ignore[index]
    for reset in census["reset"]["slots"]:  # type: ignore[index]
        if not reset["active"]:
            continue
        raw = bytes.fromhex(reset["record_hex"])
        parameter_relation = struct.unpack_from("<I", raw, 164)[0]
        parameter_index = parameter_relation - 1 if parameter_relation else None
        if parameter_index is not None:
            active_parameters.add(parameter_index)
        particle_index = struct.unpack_from("<h", raw, 94)[0]
        active_particles.add(particle_index)
        particle = struct.unpack("<HHHHHBbBB", bytes.fromhex(particle_rows[particle_index]["record_hex"]))
        base_selector, render_mode = particle[0], particle[7]
        animation_frame = struct.unpack_from("<b", raw, 96)[0]
        if render_mode == 20:
            active_sprites.update(base_selector + value for value in set(yaw_lookup))
        elif 2 <= render_mode <= 16 or 22 <= render_mode <= 36:
            active_sprites.add(base_selector + animation_frame)
        else:
            active_sprites.add(base_selector)
    if any(index < 0 or index >= 504 for index in active_sprites):
        raise ValueError(f"active presentation selector outside 504-row table: {sorted(active_sprites)}")
    for family, section in census["presentation"].items():  # type: ignore[index]
        for item in section["rows"]:
            index = int(item["index"])
            if family == "entity_parameters":
                reachable = index in active_parameters
                proof = "reset relation parameter-1 binds this entity parameter" if reachable else "no active Level 2 reset relation binds this entity parameter"
            elif family == "particle_parameters":
                reachable = index in active_particles
                proof = "active reset record byte offset 94 binds this particle parameter" if reachable else "no active Level 2 reset record binds this particle parameter"
            else:
                reachable = index in active_sprites
                proof = "active reset particle/render-mode selector expression binds this sprite selector" if reachable else "no active Level 2 render-mode expression binds this sprite selector"
            rows.append({
                "id": item["id"],
                "family": family,
                "index": index,
                "record_hex": item["record_hex"],
                "sha256": item["sha256"],
                "classification": "reachable_level2" if reachable else "mechanically_unreachable_level2",
                "owner": {"native": "remc2-sim-rs owner package", "unity": "owner presentation bridge", "authority": "Level 2 presentation cache"},
                "source": item["source"],
                "proof": proof,
            })
        roots.append({
            "id": f"PRES-ROOT-{family.upper()}",
            "family": family,
            "count": len(section["rows"]),
            "reachable_indices": sorted(index for index in (active_parameters if family == "entity_parameters" else active_particles if family == "particle_parameters" else active_sprites)),
            "classification": "reachable_level2_with_explicit_exclusions",
            "source_anchor": {"path": "presentation.bin", "package_member": "presentation.bin", "claim": "Level 2 reset relations and render-mode selector expressions bind this family"},
            "native_owner": "remc2-sim-rs owner package",
            "unity_owner": "owner presentation bridge",
        })
    return rows, roots


def build() -> dict[str, object]:
    census = json.loads(CENSUS.read_text())
    activation = json.loads(ACTIVATION.read_text())
    audio = json.loads(AUDIO.read_text())
    if census["spec"]["remc2_commit"] != COMMIT or activation["spec"]["remc2_commit"] != COMMIT:
        fail("census/activation pin does not match the Level 2 specification commit")
    active_actions, active_models, tuple_rows = authored_tuple_inputs(census)

    events_functions = source_file("remc2/engine/EventsFunctions.cpp")
    events = source_file("remc2/engine/Events.cpp")
    functions = function_bodies(events_functions)
    graph = call_graph(functions)
    dispatch = parse_dispatch_rows(events_functions, events, active_actions, active_models)
    dispatch_roots = {str(row["resolved_function"]) for row in dispatch if row["classification"] == "reachable_level2" and row["resolved_function"]}
    reachable_closure = transitive_closure(graph, dispatch_roots)
    ai_roots = ["sub_12910"]
    ai_closure = transitive_closure(graph, ai_roots)
    ai_ledger = function_ledger(functions, graph, ai_roots, "ai_helper")
