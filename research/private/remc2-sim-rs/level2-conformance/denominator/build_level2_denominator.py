"""Build the pinned Level 2 dispatch/RNG/audio/presentation denominator.

This is deliberately a mechanical, source-first ledger.  The only remc2
source accepted by this builder comes from ``git show`` at the pinned commit;
the protected upstream worktree is never read directly.  The authored/reset
census and activation closure are joins, not fixtures generated by this
builder, so changing either input changes the output and is caught by the
production-path tests.
"""

