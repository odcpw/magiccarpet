ROOT = Path(__file__).resolve().parents[5]
UPSTREAM = ROOT / "upstream/magic-carpet-2-hd"
BASE = ROOT / "research/private/remc2-sim-rs/level2-conformance"
CENSUS = BASE / "census/level2-authored-reset-census.json"
