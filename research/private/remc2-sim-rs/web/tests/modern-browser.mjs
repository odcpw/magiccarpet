import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const output = process.env.MODERN_PROOF;
if (!output?.startsWith('/')) throw new Error('Set MODERN_PROOF to an absolute disk-backed directory');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/google/chrome/chrome', headless: false, args: ['--ozone-platform=x11', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
const errors = [], routes = new Set();
const checks = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('request', r => routes.add(new URL(r.url()).pathname));
page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
const wait = (f, arg) => page.waitForFunction(f, arg, { timeout: 60000 });
const url = process.env.MODERN_URL ?? 'http://3090.bumblebee-hue.ts.net:8884/?visual=modern&automation=1';
try {
  await page.goto(url); await wait(() => !document.querySelector('#play').disabled || document.querySelector('#retry')?.hidden === false);
  assert.equal(await page.locator('#retry').isVisible(), false, await page.locator('#message').textContent());
  await page.screenshot({ path: `${output}/ready.png` });
  await page.locator('#play').click(); await wait(() => window.modernMetrics?.frames > 3);
  await page.locator('#menu').click(); await page.locator('#reset').click();
  if (await page.locator('#curtain').isVisible()) await page.locator('#pause').click();
  await wait(() => window.originalMetrics.playing);
  await page.waitForTimeout(3500);
  const initial = await page.evaluate(() => ({ metrics: window.modernMetrics, pose: window.originalState.player_pose }));
  await page.screenshot({ path: `${output}/opening.png` });
  assert.ok(initial.metrics.characters.actorCount > 0, 'native characters missing');
  assert.ok(initial.metrics.objects.buildings > 0, 'native-matching architecture missing');
  assert.equal(initial.metrics.characters.resourceCounts.Goat, 33);
  assert.equal(initial.metrics.objects.buildings, 41);
  checks.push('native reset renders the 33 goats and 41 admitted buildings');
  await page.keyboard.down('w'); await page.keyboard.down('ArrowRight'); await page.waitForTimeout(500);
  await page.keyboard.up('w'); await page.keyboard.up('ArrowRight'); await page.waitForTimeout(300);
  assert.notDeepEqual(await page.evaluate(() => window.originalState.player_pose), initial.pose);
  checks.push('native flight changes player pose');
  await page.screenshot({ path: `${output}/flight.png` });
  const mana = await page.evaluate(() => window.originalState.hud.local_player_mana);
  await page.keyboard.down('Space'); await page.waitForTimeout(350); await page.keyboard.up('Space');
  await wait(mana => window.originalState.hud.local_player_mana < mana, mana);
  checks.push('casting spends native mana');
  await page.screenshot({ path: `${output}/casting.png` });
  await page.keyboard.press('Tab'); await wait(() => window.originalState.source_menu_admission?.map_open);
  await page.screenshot({ path: `${output}/map.png` });
  await page.keyboard.press('Tab'); await wait(() => !window.originalState.source_menu_admission?.map_open);
  checks.push('source map opens and closes');
  await page.keyboard.press('Escape'); await wait(() => !window.originalMetrics.playing);
  await page.waitForTimeout(300); const tick = await page.evaluate(() => window.originalState.tick);
  await page.waitForTimeout(300); assert.equal(await page.evaluate(() => window.originalState.tick), tick);
  checks.push('pause stops native ticks');
  const saved = await page.evaluate(() => ({ tick: window.originalState.tick, pose: window.originalState.player_pose, epoch: window.modernState.epoch.toString() }));
  await page.locator('#save').click(); await wait(() => document.querySelector('#message').textContent === 'Game saved.');
  await page.locator('#pause').click(); await page.keyboard.down('w'); await page.waitForTimeout(600); await page.keyboard.up('w');
  await page.keyboard.press('Escape'); await wait(() => !window.originalMetrics.playing);
  assert.notDeepEqual(await page.evaluate(() => window.originalState.player_pose), saved.pose);
  await page.locator('#load').click();
  await wait(pose => JSON.stringify(window.originalState.player_pose) === JSON.stringify(pose), saved.pose);
  assert.equal(await page.evaluate(() => window.originalState.tick), saved.tick);
  await wait(epoch => window.modernState.epoch.toString() !== epoch, saved.epoch);
  checks.push('save/load restores pose and tick with a new Modern identity epoch');
  await page.screenshot({ path: `${output}/loaded.png` });
  const desktop = await page.evaluate(() => window.modernMetrics);

  // Use the same native controller in a touch-enabled portrait browser. This
  // validates input/layout, not physical phone GPU performance.
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  await context.addCookies(await page.context().cookies());
  const phone = await context.newPage();
  phone.on('pageerror', e => errors.push(String(e)));
  phone.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await phone.goto(url); await phone.waitForFunction(() => !document.querySelector('#play').disabled, null, { timeout: 60000 });
  await phone.locator('#play').tap(); await phone.waitForFunction(() => window.originalMetrics?.playing);
  const yaw = await phone.evaluate(() => window.originalState.player_pose.yaw);
  const cdp = await context.newCDPSession(phone);
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y, id: 1 }] });
  await touch('touchStart', 260, 390);
  for (let i = 1; i <= 6; i++) { await touch('touchMove', 260 + i * 8, 390 - i * 3); await phone.waitForTimeout(40); }
  await touch('touchEnd', 0, 0);
  await phone.waitForFunction(yaw => window.originalState.player_pose.yaw !== yaw, yaw);
  const phoneMana = await phone.evaluate(() => window.originalState.hud.local_player_mana);
  const fire = await phone.locator('[data-cast]').boundingBox(); assert.ok(fire);
  await touch('touchStart', fire.x + fire.width / 2, fire.y + fire.height / 2); await phone.waitForTimeout(350); await touch('touchEnd', 0, 0);
  await phone.waitForFunction(mana => window.originalState.hud.local_player_mana < mana, phoneMana);
  assert.ok(await phone.locator('#stage').evaluate(el => { const r = el.getBoundingClientRect(); return r.width <= innerWidth + 1 && r.height <= innerHeight + 1; }));
  await phone.screenshot({ path: `${output}/phone.png` });
  await phone.locator('#menu').tap(); await phone.waitForFunction(() => !window.originalMetrics.playing);
  await context.close();
  checks.push('portrait touch drag and Cast change authoritative native state');
  assert.ok(!routes.has('/original-api/frame') && !routes.has('/original-api/world-map'));
  checks.push('no streamed world images');
  const metrics = desktop;
  const result = { title: await page.title(), checks, initial, final: metrics, errors, routes: [...routes] };
  await writeFile(`${output}/result.json`, JSON.stringify(result, null, 2));
  const compact = ({ characters, ...rest }) => ({ ...rest, actors: characters.actorCount, resources: characters.resourceCounts });
  console.log(JSON.stringify({ title: result.title, checks, initial: compact(initial.metrics), final: compact(metrics), errors }));
  assert.deepEqual(errors, []);
} catch (e) {
  await page.screenshot({ path: `${output}/failure.png` });
  console.error(e); console.error(JSON.stringify({ errors, message: await page.locator('#message').textContent() })); process.exitCode = 1;
} finally { await browser.close(); }
