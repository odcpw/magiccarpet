class GuardError(Exception):
    """A profile or sealed identity violates the contract."""


def fail(message: str) -> None:
    raise GuardError(message)


def sha256(path: Path) -> str:
    try:
        data = path.read_bytes()
    except OSError as exc:
        fail(f"cannot read sealed artifact {path}: {exc}")
    return hashlib.sha256(data).hexdigest()


def require(condition: bool, message: str) -> None:
    if not condition:
        fail(message)


def load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"invalid JSON {path}: {exc}")
    require(type(value) is dict, f"{path}: root must be an object")
    return value


def assert_source_pin() -> None:
    require(UPSTREAM.is_dir(), f"upstream checkout is missing: {UPSTREAM}")
    try:
        result = subprocess.run(
            ["git", "-C", str(UPSTREAM), "rev-parse", "HEAD"],
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError as exc:
        fail(f"cannot inspect pinned remc2 checkout: {exc}")
    require(result.returncode == 0, "cannot resolve remc2 checkout HEAD")
    actual = result.stdout.strip()
    require(
        actual == PINNED_REMC2_COMMIT,
        f"remc2 HEAD changed: expected {PINNED_REMC2_COMMIT}, got {actual or '<empty>'}",
    )
    source_tokens = {
        "remc2/engine/MapType.h": ("MapType_t", "Day = 0"),
        "remc2/engine/Level.cpp": ("LoadLevel_555D0",),
        "remc2/engine/EventsFunctions.cpp": (
            "sub_47FC0_load_screen",
            "ClearGraphicsBuffer_72883((void*)pdwScreenBuffer_351628, 320, 200",
            "sub_90478_VGA_Blit320",
        ),
    }
    for source_path, tokens in source_tokens.items():
        result = subprocess.run(
            ["git", "-C", str(UPSTREAM), "show", f"{PINNED_REMC2_COMMIT}:{source_path}"],
            check=False,
            capture_output=True,
            text=True,
        )
        require(result.returncode == 0, f"cannot read pinned source: {source_path}")
        for token in tokens:
            require(token in result.stdout, f"pinned source anchor changed or is unreadable: {source_path} ({token})")


def assert_profile(profile: dict[str, Any]) -> None:
    require(profile.get("schema") == "mc2-level2-profile-contract/v1", "wrong Level 2 profile schema")
    specification = profile.get("specification")
    require(type(specification) is dict, "profile.specification must be an object")
    require(
        specification.get("remc2_commit") == PINNED_REMC2_COMMIT,
        "profile specification is not pinned to the accepted remc2 commit",
    )
    require(specification.get("source_anchors") == EXPECTED_SOURCE_ANCHORS, "profile source anchors changed")
    actual = profile.get("profile")
    require(actual == EXPECTED_PROFILE, "Level 2 profile values changed; broaden with a reviewed matrix revision")

    scope = profile.get("scope")
    require(type(scope) is dict, "profile.scope must be an object")
    for key in ("inclusions", "nonclaims", "broadening_requires"):
        value = scope.get(key)
        require(type(value) is list and value and all(isinstance(item, str) and item for item in value), f"scope.{key} must be non-empty strings")
    require(any("does not claim" in item for item in scope["nonclaims"]), "scope must state the Level 2 nonclaim")
    require(any("later matrix" in item for item in scope["broadening_requires"]), "scope must require a later matrix for broadening")

    current = profile.get("sealed_level1", {}).get("current_checks")
    require(type(current) is dict and current.get("regenerable") is True, "current Level 1 checks must be marked regenerable")
    require(current.get("commands") == EXPECTED_CURRENT_COMMANDS, "current Level 1 command bundle changed")


def assert_historical_receipts(profile: dict[str, Any]) -> dict[str, Any]:
    sealed = profile.get("sealed_level1")
    require(type(sealed) is dict, "sealed_level1 must be an object")
    history = sealed.get("historical_receipts")
    require(type(history) is dict and history.get("immutable") is True, "historical Level 1 receipts must be immutable")
    matrix = history.get("matrix")
    require(type(matrix) is dict, "historical matrix identity is missing")
    matrix_path = ROOT / str(matrix.get("path", ""))
    require(matrix.get("rows") == 182 and matrix.get("exact_rows") == 182 and matrix.get("structured_exclusions") == 29, "sealed Level 1 matrix totals changed")
    require(sha256(matrix_path) == matrix.get("sha256"), "sealed Level 1 matrix hash changed")

    closure = history.get("closure_contract")
    require(type(closure) is dict, "historical closure identity is missing")
    closure_path = ROOT / str(closure.get("path", ""))
    require(sha256(closure_path) == closure.get("file_sha256"), "sealed Level 1 closure contract hash changed")
    closure_doc = load_json(closure_path)
    require(closure_doc.get("contract_sha256") == closure.get("declared_contract_sha256"), "closure contract declared identity changed")

    policy = history.get("qualification_policy")
    require(type(policy) is dict, "historical qualification identity is missing")
    policy_path = ROOT / str(policy.get("path", ""))
    require(sha256(policy_path) == policy.get("file_sha256"), "sealed Level 1 qualification policy hash changed")
    policy_doc = load_json(policy_path)
    require(policy_doc.get("policy_sha256") == policy.get("declared_policy_sha256"), "qualification policy declared identity changed")
    acceptance = policy_doc.get("acceptance", {})
    require(acceptance.get("required_clean_runs") == policy.get("required_clean_runs"), "qualification clean-run requirement changed")
    require(acceptance.get("run_b_required") == policy.get("run_b_required"), "qualification run-B requirement changed")
    require(acceptance.get("run_b_permitted") == policy.get("run_b_permitted"), "qualification run-B permission changed")

    cache = history.get("cache_identity")
    require(type(cache) is dict, "historical cache identity is missing")
    cache_path = ROOT / str(cache.get("path", ""))
    require(sha256(cache_path) == cache.get("file_sha256"), "sealed Level 1 cache identity hash changed")
    cache_doc = load_json(cache_path)
    require(cache_doc.get("seal_sha256") == cache.get("declared_seal_sha256"), "cache declared seal changed")
    package = history.get("owner_package")
    require(type(package) is dict, "historical owner package identity is missing")
    package_path = ROOT / str(package.get("path", ""))
    require(sha256(package_path) == package.get("file_sha256"), "sealed owner package manifest hash changed")
    package_doc = load_json(package_path)
    level = package_doc.get("level", {})
    require(level.get("external") == 1 and level.get("internal") == 0, "sealed owner package level identity changed")
    require(package_doc.get("schema") == "mc2-owner-level-export/v2", "sealed owner package schema changed")
    asset_closure = history.get("asset_closure")
    require(type(asset_closure) is dict, "historical asset closure identity is missing")
    asset_closure_path = ROOT / str(asset_closure.get("path", ""))
    require(sha256(asset_closure_path) == asset_closure.get("file_sha256"), "sealed asset closure hash changed")
    asset_closure_doc = load_json(asset_closure_path)
    require(asset_closure_doc.get("closure_sha256") == asset_closure.get("declared_closure_sha256"), "asset closure declared identity changed")
    abi = history.get("abi")
    require(type(abi) is dict, "historical native ABI identity is missing")
    abi_header_path = ROOT / str(abi.get("header_path", ""))
    require(sha256(abi_header_path) == abi.get("header_sha256"), "sealed native ABI header hash changed")
    require(
        abi.get("event_code_range") == {"first": 0, "last": 38},
        "sealed native ABI event-code range changed",
    )
    require(
        abi.get("layout_tests") == [
            "layouts_and_versions_are_stable",
            "c_header_compiles_and_locks_the_rust_layout",
            "presentation_frame_abi_is_revisioned_complete_idempotent_and_fail_closed",
        ],
        "sealed native ABI witness tests changed",
    )
    return {
        "matrix": matrix_path.as_posix(),
        "closure_contract": closure_path.as_posix(),
        "qualification_policy": policy_path.as_posix(),
        "cache_identity": cache_path.as_posix(),
        "owner_package": package_path.as_posix(),
        "asset_closure": asset_closure_path.as_posix(),
        "abi_header": abi_header_path.as_posix(),
    }


def run_current_checks() -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    for check_id, command, predicate in CURRENT_CHECKS:
        try:
            process = subprocess.run(
                command,
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
            )
        except OSError as exc:
            fail(f"current check {check_id} could not start: {exc}")
        output = (process.stdout + process.stderr).strip()
        passed = process.returncode == 0
        if passed and check_id == "level1-closed-matrix":
            try:
                passed = bool(predicate(process.stdout))
            except (ValueError, TypeError, json.JSONDecodeError):
                passed = False
        elif passed:
            passed = bool(predicate(output))
        results.append({"id": check_id, "status": "PASS" if passed else "FAIL", "command": " ".join(command)})
        if not passed:
            detail = output[-1200:] if output else "<no output>"
            fail(f"current check {check_id} failed: {detail}")
    return results


def verify(*, run_tests: bool) -> dict[str, Any]:
    assert_source_pin()
    profile = load_json(PROFILE_PATH)
    assert_profile(profile)
    sealed_paths = assert_historical_receipts(profile)
    checks = run_current_checks() if run_tests else []
    return {
        "ok": True,
        "profile": "Level 2 / external 2 / internal 1 / Day",
        "historical_receipts": {"status": "PASS", "immutable": True, "paths": sealed_paths},
        "current_checks": {"status": "PASS" if run_tests else "NOT_RUN", "checks": checks},
        "source_commit": PINNED_REMC2_COMMIT,
    }


def main(argv: list[str] | None = None) -> int:
    global PROFILE_PATH
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", type=Path, default=PROFILE_PATH)
    parser.add_argument("--no-current-tests", action="store_true", help="only verify profile, source pin, and immutable Level 1 identities")
    parser.add_argument("--json", action="store_true", help="emit one machine-readable result")
    args = parser.parse_args(argv)
    PROFILE_PATH = args.profile.resolve()
    try:
        result = verify(run_tests=not args.no_current_tests)
    except GuardError as exc:
        result = {"ok": False, "error": str(exc)}
        if args.json:
            print(json.dumps(result, sort_keys=True))
        else:
            print(f"LEVEL2 GUARD FAIL: {exc}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(result, sort_keys=True))
    else:
        print("LEVEL2 GUARD PASS: external level 2 -> internal index 1, Day, offline, 320x200")
        print("  historical Level 1 receipts: PASS (immutable hashes)")
        if not args.no_current_tests:
            print("  current Level 1 checks: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
