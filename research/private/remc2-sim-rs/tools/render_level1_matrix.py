#!/usr/bin/env python3
"""Render the canonical Level 1 conformance JSON as reviewable Markdown."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

import validate_level1_matrix as validator


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "level1-conformance" / "level1-conformance-matrix.json"
DEFAULT_OUTPUT = ROOT / "level1-conformance" / "LEVEL1-CONFORMANCE-MATRIX.md"
CLASSIFICATIONS = ("Exact", "Partial", "Missing", "Wrong", "Unproved")


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def dispatch_label(row: dict[str, object]) -> str:
    dispatch = row["source"]["dispatch"]
    if dispatch is None:
        return "—"
    return f'{dispatch["class"]}/{dispatch["model"]}/{dispatch["action_slot"]}'


def evidence_label(row: dict[str, object]) -> str:
    executable = [
        binding["test"]
        for binding in row["evidence_bindings"]
        if binding["kind"] in {"rust-test", "unity-test", "python-test"}
    ]
    if not executable:
        return "—"
    suffix = f" (+{len(executable) - 1})" if len(executable) > 1 else ""
    return f"`{cell(executable[0])}`{suffix}"


def render(
    document: dict[str, object],
    source_bytes: bytes,
    validation: dict[str, object],
) -> str:
    meta = document["meta"]
    rows = document["rows"]
    exclusions = document["exclusions"]
    totals = Counter(row["classification"] for row in rows)
    by_subsystem: dict[str, Counter[str]] = {}
    for row in rows:
        by_subsystem.setdefault(row["subsystem"], Counter())[row["classification"]] += 1

    lines = [
        "# Level 1 conformance matrix (generated view)",
        "",
        f'Generated from canonical matrix: {meta["generated"]}',
        f'Schema: `{document["schema"]["id"]}` v{document["schema"]["version"]}',
        f'Specification: remc2 at `{meta["remc2_commit"]}`',
        f'Canonical SHA-256: `{hashlib.sha256(source_bytes).hexdigest()}`',
        "Canonical machine-readable matrix: [`level1-conformance-matrix.json`](level1-conformance-matrix.json)",
        "",
        "> Do not edit this file by hand. Run `python3 tools/render_level1_matrix.py` from the Rust workspace. `--check` fails when this view drifts from the canonical JSON.",
        "",
        "## Verdict",
        "",
        f'Bounded private Level 1 conformance is closed: **{validation["exact_rows"]}/{validation["rows"]} Exact**, {validation["non_exact_rows"]} non-Exact rows, and {validation["exclusions"]} structured exclusions with mechanical proofs. This does not broaden the fixed single-player Night profile or any explicit nonclaim.',
        "",
        "## Method",
        "",
        meta["census_method"],
        "",
        f'Owner data profile: `{meta["owner_package"]}`.',
        "",
        f'Evidence bindings resolve against the validator-captured {validation["cargo_tests"]}-test Cargo inventory. Every Exact row has a resolving Rust test and no non-executable binding.',
        "",
        "## Totals",
        "",
        "| Classification | Rows |",
        "|---|---:|",
    ]
    lines.extend(f"| {name} | {totals[name]} |" for name in CLASSIFICATIONS)
    lines.extend([
        f"| **Total** | **{len(rows)}** |",
        "",
        f'Authored census: {len(document["authored_census"]["nonzero_indices"])}/308 indices partitioned. Dispatch census: {len(document["dispatch_census"]["slots"])}/845 mechanical slots partitioned. Exclusions: {len(exclusions)}.',
        "",
        "| Subsystem | Exact | Partial | Missing | Wrong | Unproved | Total |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ])
    for subsystem, counts in by_subsystem.items():
        values = [counts[name] for name in CLASSIFICATIONS]
        lines.append(f'| {cell(subsystem)} | {" | ".join(map(str, values))} | {sum(values)} |')

    lines.extend(["", "## Rows", ""])
    current = None
    for row in rows:
        if row["subsystem"] != current:
            if current is not None:
                lines.append("")
            current = row["subsystem"]
            lines.extend([
                f"### {current}",
                "",
                "| Row | Title | Reachability | Class/model/slot | Classification | Source | Executable evidence |",
                "|---|---|---|---|---|---|---|",
            ])
        source = row["source"]
        lines.append(
            f'| `{cell(row["id"])}` | {cell(row["title"])} | {cell(row["reachability"]["status"])} | '
            f'{dispatch_label(row)} | **{cell(row["classification"])}** | '
            f'`{cell(source["path"])}:{cell(source["lines"])}` | {evidence_label(row)} |'
        )
    lines.extend(["", "## Structured exclusions", "", "| ID | Scope | Mechanical proof | Source anchors |", "|---|---|---|---|"])
    for exclusion in exclusions:
        anchors = "; ".join(exclusion["source_anchors"])
        lines.append(
            f'| `{cell(exclusion["id"])}` | {cell(exclusion["scope"])} | '
            f'{cell(exclusion["mechanical_proof"])} | {cell(anchors)} |'
        )
    lines.extend(["", "## Validator contract", ""])
    for check in document["validator_contract"]["checks"]:
        lines.append(f'- [x] `{cell(check["id"])}`: {cell(check["rule"])}')
    lines.append("")
    return "\n".join(lines)


def render_document(
    document: dict[str, object],
    source_bytes: bytes,
    validation: dict[str, object],
    *,
    profile: validator.MatrixValidationProfile | None = None,
) -> str:
    """Render any validated matrix, keeping the historical Level 1 view intact."""

    if profile is None or profile.schema_id == validator.SCHEMA_ID:
        return render(document, source_bytes, validation)

    meta = document["meta"]
    rows = document["rows"]
    exclusions = document["exclusions"]
    totals = Counter(row["classification"] for row in rows)
    by_subsystem: dict[str, Counter[str]] = {}
    for row in rows:
        by_subsystem.setdefault(row["subsystem"], Counter())[row["classification"]] += 1
    schema = document["schema"]
    lines = [
        f'# {schema["id"]} conformance matrix (generated view)',
        "",
        f'Generated from canonical matrix: {meta["generated"]}',
        f'Schema: `{schema["id"]}` v{schema["version"]}',
        f'Specification: remc2 at `{meta["remc2_commit"]}`',
        f'Canonical SHA-256: `{hashlib.sha256(source_bytes).hexdigest()}`',
        "",
        "> Do not edit this file by hand. Run the renderer with an explicit matrix profile.",
        "",
        "## Verdict",
        "",
        (
            f'Open conformance status: **{validation["exact_rows"]}/{validation["rows"]} Exact**, '
            f'{validation["non_exact_rows"]} non-Exact rows, and {validation["exclusions"]} structured exclusions. '
            "A non-closed matrix makes no completeness claim."
        ),
        "",
        "## Method",
        "",
        meta["census_method"],
        "",
        f'Evidence bindings resolve against the declared {validation["cargo_tests"]}-test external inventory.',
        "",
        "## Totals",
        "",
        "| Classification | Rows |",
        "|---|---:|",
    ]
    lines.extend(f"| {name} | {totals[name]} |" for name in CLASSIFICATIONS)
    lines.extend([
        f"| **Total** | **{len(rows)}** |",
        "",
        f'Authored census: {len(document["authored_census"]["nonzero_indices"])} indices partitioned. '
        f'Dispatch census: {len(document["dispatch_census"]["slots"])} mechanical slots partitioned. '
        f'Exclusions: {len(exclusions)}.',
        "",
        "| Subsystem | Exact | Partial | Missing | Wrong | Unproved | Total |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ])
    for subsystem, counts in by_subsystem.items():
        values = [counts[name] for name in CLASSIFICATIONS]
        lines.append(f'| {cell(subsystem)} | {" | ".join(map(str, values))} | {sum(values)} |')

    lines.extend(["", "## Rows", ""])
    current = None
    for row in rows:
        if row["subsystem"] != current:
            if current is not None:
                lines.append("")
            current = row["subsystem"]
            lines.extend([
                f"### {current}",
                "",
                "| Row | Title | Reachability | Class/model/slot | Classification | Source | Executable evidence |",
                "|---|---|---|---|---|---|---|",
            ])
        source = row["source"]
        lines.append(
            f'| `{cell(row["id"])}` | {cell(row["title"])} | {cell(row["reachability"]["status"])} | '
            f'{dispatch_label(row)} | **{cell(row["classification"])}** | '
            f'`{cell(source["path"])}:{cell(source["lines"])}` | {evidence_label(row)} |'
        )
    lines.extend(["", "## Structured exclusions", "", "| ID | Scope | Mechanical proof | Source anchors |", "|---|---|---|---|"])
    for exclusion in exclusions:
        anchors = "; ".join(exclusion["source_anchors"])
        lines.append(
            f'| `{cell(exclusion["id"])}` | {cell(exclusion["scope"])} | '
            f'{cell(exclusion["mechanical_proof"])} | {cell(anchors)} |'
        )
    lines.extend(["", "## Validator contract", ""])
    for check in document["validator_contract"]["checks"]:
        lines.append(f'- [x] `{cell(check["id"])}`: {cell(check["rule"])}')
    lines.append("")
    return "\n".join(lines)


def render_matrix(
    document: dict[str, object],
    source_bytes: bytes,
    validation: dict[str, object],
    profile: validator.MatrixValidationProfile,
) -> str:
    """Explicit generic rendering entry point used by open matrix tooling."""

    return render_document(document, source_bytes, validation, profile=profile)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--profile",
        type=Path,
        help="explicit JSON matrix-validation profile; without it use sealed Level 1 policy",
    )
    parser.add_argument(
        "--evidence-inventory",
        type=Path,
        help="reviewed JSON inventory of external executable evidence names",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source_bytes = args.input.read_bytes()
    profile = (
        validator.profile_from_json(args.profile.resolve())
        if args.profile is not None
        else validator.level1_validation_profile()
    )
    inventory = (
        validator.load_external_evidence_inventory(args.evidence_inventory.resolve())
        if args.evidence_inventory is not None
        else validator.capture_cargo_test_inventory(ROOT)
    )
    try:
        validation = (
            validator.require_closed(args.input, inventory, profile)
            if args.profile is None
            else validator.validate_file(args.input, inventory, profile)
        )
    except validator.ValidationError as error:
        print(f"INVALID {args.input}: {error}", file=sys.stderr)
        return 1
    rendered = render_document(
        json.loads(source_bytes), source_bytes, validation, profile=profile
    )
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            print(f"STALE {args.output}")
            return 1
        print(f"PASS {args.output}")
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    print(f"WROTE {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
